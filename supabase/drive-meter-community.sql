-- VOZIO Drive Meter: svetové komunitné štatistiky
-- Spusti tento SQL v Supabase SQL Editor projektu VOZIO.
create table if not exists public.drive_meter_trips (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  country text not null check (char_length(country) between 1 and 60),
  city text not null check (char_length(city) between 1 and 80),
  road_type text not null check (road_type in ('Mesto','Mimo obce','Diaľnica','Horská cesta','Okruh')),
  driving_style text not null check (driving_style in ('Plynulá','Úsporná','Bežná','Dynamická')),
  distance_km numeric(9,3) not null check (distance_km >= 0 and distance_km <= 5000),
  duration_seconds integer not null check (duration_seconds >= 0 and duration_seconds <= 172800),
  average_speed_kmh numeric(6,2) not null check (average_speed_kmh >= 0 and average_speed_kmh <= 300),
  max_speed_kmh numeric(6,1) not null check (max_speed_kmh >= 0 and max_speed_kmh <= 400),
  created_at timestamptz not null default now()
);
alter table public.drive_meter_trips enable row level security;
revoke all on public.drive_meter_trips from anon, authenticated;
grant insert on public.drive_meter_trips to authenticated;
grant usage, select on sequence public.drive_meter_trips_id_seq to authenticated;
drop policy if exists "users insert own opted-in trips" on public.drive_meter_trips;
create policy "users insert own opted-in trips"
on public.drive_meter_trips for insert to authenticated
with check (auth.uid() = user_id);

-- Verejný view sprístupňuje iba agregované skupiny, nie jednotlivé jazdy či účty.
create or replace view public.drive_meter_public_stats as
select country, city, road_type, driving_style,
       count(*)::bigint as trip_count,
       round(sum(distance_km),1) as total_km,
       round(avg(average_speed_kmh),1) as avg_speed_kmh
from public.drive_meter_trips
group by country, city, road_type, driving_style
having count(*) >= 3;
grant select on public.drive_meter_public_stats to anon, authenticated;
